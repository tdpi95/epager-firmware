#!/usr/bin/env python3
"""Compile the built-in clock faces (components/ui_common/faces/<name>/face.json) into
components/ui_common/src/ui_face_builtin.c. Never edit that file by hand.

    python tools/clock_face/gen_builtin.py [--check]     (--check: exit 1 if the file differs from what would be written)
"""
from __future__ import annotations

import argparse
import json
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parents[1]))

from clock_face import build as B  # noqa: E402

REPO = Path(__file__).resolve().parents[2]
FACES = REPO / "components/ui_common/faces"
OUT = REPO / "components/ui_common/src/ui_face_builtin.c"
BANNER = "GENERATED by tools/clock_face/gen_builtin.py from components/ui_common/faces - DO NOT EDIT"
LAYOUT = {"paper": "mono", "lcd": "colour"}


def render() -> str:
    lines = [f"/* {BANNER} */", '#include "ui_face_builtin.h"', '#include "ui_priv.h"', ""]
    tables: dict[str, list[tuple[str, str, int]]] = {"mono": [], "colour": []}
    for d in sorted(p for p in FACES.iterdir() if (p / "face.json").exists()):
        src = json.loads((d / "face.json").read_text())
        for board in LAYOUT:
            if board not in src["boards"]:
                continue
            data = B.build(src, d, board)
            name = f"face_{d.name}_{board}"
            lines.append(f"#if UI_HAS_{LAYOUT[board].upper()}")
            lines.append(f"/* {src['meta']['id']} for the {board} board: {len(data)} bytes */")
            lines.append(f"static const uint8_t {name}[] __attribute__((aligned(4))) = {{")
            for i in range(0, len(data), 16):
                lines.append("    " + ", ".join(f"0x{b:02x}" for b in data[i:i + 16]) + ",")
            lines += ["};", "#endif", ""]
            tables[LAYOUT[board]].append((src["meta"]["id"], name, len(data)))
    for layout, rows in tables.items():
        lines.append(f"#if UI_HAS_{layout.upper()}")
        lines.append(f"const ui_builtin_face_t ui_builtin_faces_{layout}[] = {{")
        for fid, name, n in rows:
            lines.append(f'    {{"{fid}", {name}, sizeof({name})}},')
        lines += ["};", f"const size_t ui_builtin_faces_{layout}_count = sizeof(ui_builtin_faces_{layout}) / sizeof(ui_builtin_faces_{layout}[0]);",
                  "#else", f"const ui_builtin_face_t ui_builtin_faces_{layout}[1] = {{{{0}}}};",
                  f"const size_t ui_builtin_faces_{layout}_count = 0;", "#endif", ""]
    return "\n".join(lines)


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--check", action="store_true")
    args = ap.parse_args()
    text = render()
    if args.check:
        if not OUT.exists() or OUT.read_text() != text:
            print(f"stale: run tools/clock_face/gen_builtin.py ({OUT.relative_to(REPO)})")
            return 1
        print("built-in faces up to date")
        return 0
    OUT.write_text(text)
    print(f"wrote {OUT.relative_to(REPO)}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
