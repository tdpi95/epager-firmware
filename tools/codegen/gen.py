SCHEMA_BASE = "https://epager.local/contracts/schemas/"

FT = {"u8": "PROTO_FT_U8", "u16": "PROTO_FT_U16", "u32": "PROTO_FT_U32", "i16": "PROTO_FT_I16",
      "i32": "PROTO_FT_I32", "bool": "PROTO_FT_BOOL", "str": "PROTO_FT_STR", "id": "PROTO_FT_ID",
      "text": "PROTO_FT_TEXT", "bytes": "PROTO_FT_BYTES", "struct": "PROTO_FT_STRUCT"}
KIND = {"request": "PROTO_KIND_REQUEST", "response": "PROTO_KIND_RESPONSE", "event": "PROTO_KIND_EVENT",
        "read": "PROTO_KIND_READ", "error": "PROTO_KIND_ERROR"}
CHAN = {"any": "PROTO_CHAN_ANY", "capabilities": "PROTO_CHAN_CAPABILITIES", "config": "PROTO_CHAN_CONFIG",
        "notification": "PROTO_CHAN_NOTIFICATION", "transfer": "PROTO_CHAN_TRANSFER", "status": "PROTO_CHAN_STATUS"}


def cname(s: str) -> str:
    return s.upper().replace(".", "_")


def pack_version(v: str) -> int:
    major, minor, patch = (int(x) for x in v.split("."))
    return major << 16 | minor << 8 | patch


def uuid_le_bytes(u: str) -> str:
    return ", ".join(f"0x{b:02x}" for b in reversed(uuid.UUID(u).bytes))


# ----------------------------------------------------------------------------- C header

def gen_header(reg: R.Registry, gatt: dict) -> str:
    L = [f"/* {BANNER} */", "#pragma once", "", '#include "epager/proto_desc.h"', "",
         "#ifdef __cplusplus", 'extern "C" {', "#endif", "",
         f'#define PROTO_CONTRACT_VERSION "{reg.contract_version}"',
         f"#define PROTO_MAJOR {reg.proto_major}", f"#define PROTO_UNICODE_VERSION \"{unicodedata.unidata_version}\"", "",
         "/* Limits */"]
    for k, v in reg.limits.items():
        L.append(f"#define PROTO_LIMIT_{cname(k)} {v}u")
    L += ["", "/* Status codes */", "typedef enum {"]
    for s in reg.raw["status_codes"]:
        L.append(f"    PROTO_{s['name']} = {s['id']},")
    L += ["    PROTO_STATUS_COUNT", "} proto_status_t;", "", "/* Message types */", "typedef enum {"]
    for m in reg.messages:
        L.append(f"    PROTO_MSG_{m.name} = 0x{m.id:02X},")
    L += ["} proto_msg_type_t;", "", "/* Field tags per message */"]
    for m in reg.messages:
        for f in m.fields:
            L.append(f"#define PROTO_TAG_{m.name}_{cname(f.name)} {f.tag}")
    L += ["", "/* Field tags per struct */"]
    for sname, fields in reg.structs.items():
        for f in fields:
            L.append(f"#define PROTO_TAG_{cname(sname)}_{cname(f.name)} {f.tag}")
    L += ["", "/* Enums (receivers map unknown values to *_FALLBACK) */"]
    for ename, e in reg.enums.items():
        for v in e["values"]:
            L.append(f"#define PROTO_{cname(ename)}_{cname(v['name'])} {v['value']}")
        L.append(f"#define PROTO_{cname(ename)}_FALLBACK {e['fallback']}")
    L += ["", "/* Bitmasks */"]
    for bname, bits in reg.bitmasks.items():
        for b in bits:
            L.append(f"#define PROTO_{cname(bname)}_{cname(b['name'])} (1u << {b['bit']})")
    L += ["", "/* Config keys */"]
    for k in reg.config_keys:
        L.append(f"#define PROTO_CFG_{cname(k['name'])} {k['id']}")
    str_max = max([k["max_len"] for k in reg.config_keys if k["type"] == "str"], default=0)
    L += [f"#define PROTO_CFG_KEY_COUNT {len(reg.config_keys)}u",
          f"#define PROTO_CFG_STR_MAX_LEN {str_max}u",
          "/* Contract versions packed as major << 16 | minor << 8 | patch (config key `since`) */",
          f"#define PROTO_CONTRACT_VERSION_PACKED 0x{pack_version(reg.contract_version):06x}u"]
    L += ["", "/* GATT UUIDs, little-endian byte order (as BLE_UUID128_INIT expects) */"]
    svc = gatt["service"]
    L.append(f"#define PROTO_UUID_SERVICE_LE {uuid_le_bytes(svc['uuid'])}")
    for c in svc["characteristics"]:
        L.append(f"#define PROTO_UUID_CHR_{cname(c['name'])}_LE {uuid_le_bytes(c['uuid'])}")
    for k, v in gatt["ancs"].items():
        L.append(f"#define PROTO_UUID_ANCS_{cname(k)}_LE {uuid_le_bytes(v)}")
    L.append(f"#define PROTO_ADV_NAME_PREFIX \"{gatt['advertising']['name_prefix']}\"")
    L += ["", "/* Text rules (protocol.md section 8) */",
          f"#define PROTO_TEXT_PLACEHOLDER 0x{R.hexcp(reg.text['placeholder']):04X}u",
          f"#define PROTO_TEXT_ELLIPSIS 0x{R.hexcp(reg.text['ellipsis']):04X}u",
          f"#define PROTO_TEXT_MARK_FIRST 0x{R.hexcp(reg.text['combining_range'][0]):04X}u",
          f"#define PROTO_TEXT_MARK_LAST 0x{R.hexcp(reg.text['combining_range'][1]):04X}u",
          f"#define PROTO_TEXT_MAX_MARKS {reg.text['max_combining_run']}u",
          f"#define PROTO_TEXT_ZWJ 0x{R.hexcp(reg.text['zwj']):04X}u",
          f"#define PROTO_TEXT_RI_FIRST 0x{R.hexcp(reg.text['regional_indicator_range'][0]):04X}u",
          f"#define PROTO_TEXT_RI_LAST 0x{R.hexcp(reg.text['regional_indicator_range'][1]):04X}u",
          f"#define PROTO_TEXT_FLAG_GLYPH 0x{R.hexcp(reg.text['flag_glyph']):04X}u", "",
          "typedef struct { uint32_t key; uint16_t composed; } proto_compose_pair_t; /* key = base << 10 | (mark - MARK_FIRST) */",
          "typedef struct { uint32_t first, last; } proto_cp_range_t;", "",
          "extern const proto_msg_desc_t proto_messages[];",
          "extern const size_t proto_messages_count;",
          "extern const proto_cfg_key_desc_t proto_cfg_keys[];",
          "extern const size_t proto_cfg_keys_count;",
          "extern const char *const proto_status_names[PROTO_STATUS_COUNT];",
          "extern const proto_compose_pair_t proto_compose_pairs[];",
          "extern const size_t proto_compose_pairs_count;",
          "extern const uint8_t proto_mark_ccc[PROTO_TEXT_MARK_LAST - PROTO_TEXT_MARK_FIRST + 1];",
          "extern const proto_cp_range_t proto_renderable_ranges[];",
          "extern const proto_cp_range_t proto_removed_ranges[];",
          "extern const size_t proto_removed_ranges_count;",
          "extern const size_t proto_renderable_ranges_count;",
          "extern const proto_cp_range_t proto_emoji_ranges[];",
          "extern const size_t proto_emoji_ranges_count;", "",
          "#ifdef __cplusplus", "}", "#endif", ""]
    return "\n".join(L)


# ----------------------------------------------------------------------------- C tables

def field_initializer(f: R.Field, owner: str) -> str:
    flags = []
    if f.required:
        flags.append("PROTO_F_REQUIRED")
    if f.repeated:
        flags.append("PROTO_F_REPEATED")
    if f.min is not None:
        flags.append("PROTO_F_HAS_MIN")
    if f.max is not None:
        flags.append("PROTO_F_HAS_MAX")
    for v in (f.min, f.max):
        if v is not None and not -2**31 <= v < 2**31:
            raise ValueError(f"{owner}.{f.name}: min/max must fit int32")
    nested = f"&proto_struct_{f.struct}" if f.type == "struct" else "NULL"
    return (f'    {{ .name = "{f.name}", .tag = {f.tag}, .type = {FT[f.type]}, '
            f'.flags = {" | ".join(flags) or "0"}, .min_len = {f.eff_min_len or 0}, '
            f'.max_len = {f.eff_max_len or 0}, .min = {f.min or 0}, .max = {f.max or 0}, .nested = {nested} }},')


def struct_order(reg: R.Registry) -> list[str]:
    """Structs ordered so nested ones are defined first."""
    order: list[str] = []

    def visit(n: str) -> None:
        if n in order:
            return
        for f in reg.structs[n]:
            if f.type == "struct":
                visit(f.struct)
        order.append(n)

    for n in reg.structs:
        visit(n)
    return order


def gen_source(reg: R.Registry) -> str:
    L = [f"/* {BANNER} */", '#include "epager/proto_gen.h"', ""]
    for sname in struct_order(reg):
        fields = sorted(reg.structs[sname], key=lambda f: f.tag)
        L.append(f"static const proto_field_desc_t proto_fields_{sname}[] = {{")
        L += [field_initializer(f, sname) for f in fields]
        L.append("};")
        L.append(f'static const proto_struct_desc_t proto_struct_{sname} = '
                 f'{{ "{sname}", proto_fields_{sname}, {len(fields)} }};')
        L.append("")
    for m in reg.messages:
        if not m.fields:
            continue
        L.append(f"static const proto_field_desc_t proto_fields_msg_{m.name}[] = {{")
        L += [field_initializer(f, m.name) for f in sorted(m.fields, key=lambda f: f.tag)]
        L.append("};")
    L += ["", "const proto_msg_desc_t proto_messages[] = {"]
    for m in sorted(reg.messages, key=lambda m: m.id):
        fields = f"proto_fields_msg_{m.name}" if m.fields else "NULL"
        L.append(f'    {{ 0x{m.id:02X}, {KIND[m.kind]}, {CHAN[m.channel]}, '
                 f'{{ "{m.name}", {fields}, {len(m.fields)} }} }},')
    L += ["};", "const size_t proto_messages_count = sizeof(proto_messages) / sizeof(proto_messages[0]);", ""]

    variants = {v["name"]: v["value"] for v in reg.enums["variant"]["values"]}
    for k in reg.config_keys:
        if "enum" in k:
            vals = ", ".join(str(v["value"]) for v in reg.enums[k["enum"]]["values"])
            L.append(f"static const uint8_t proto_cfg_enum_{cname(k['name']).lower()}[] = {{ {vals} }};")
    L.append("const proto_cfg_key_desc_t proto_cfg_keys[] = {")
    for k in reg.config_keys:
        flags = []
        if k.get("read_only"):
            flags.append("PROTO_CFG_READ_ONLY")
        if "min" in k:
            flags.append("PROTO_CFG_HAS_MIN")
        if "max" in k:
            flags.append("PROTO_CFG_HAS_MAX")
        mask = 0
        for v in k.get("variants", []):
            mask |= 1 << variants[v]
        if "enum" in k:
            ev = f"proto_cfg_enum_{cname(k['name']).lower()}"
            en = f"{ev}, sizeof({ev})"
        else:
            en = "NULL, 0"
        d = k["default"]
        dint = int(d) if not isinstance(d, str) else 0
        dstr = json.dumps(d) if isinstance(d, str) else "NULL"
        L.append(f'    {{ "{k["name"]}", {k["id"]}, {FT[k["type"]]}, {" | ".join(flags) or "0"}, '
                 f'{k.get("max_len", 0)}, {k.get("min", 0)}, {k.get("max", 0)}, 0x{mask:x}u, {en}, {dint}, {dstr}, '
                 f'0x{pack_version(k["since"]):06x}u }},')
    L += ["};", "const size_t proto_cfg_keys_count = sizeof(proto_cfg_keys) / sizeof(proto_cfg_keys[0]);", ""]

    L.append("const char *const proto_status_names[PROTO_STATUS_COUNT] = {")
    for s in reg.raw["status_codes"]:
        L.append(f'    [{s["id"]}] = "{s["name"]}",')
    L += ["};", ""]

    rules = T.TextRules(reg)
    for name, rs in (("renderable_ranges", rules.ranges), ("removed_ranges", rules.removed), ("emoji_ranges", rules.emoji)):
        # proto_util.c binary-searches these tables
        assert all(a <= b for a, b in rs) and all(rs[i][1] < rs[i + 1][0] for i in range(len(rs) - 1)), \
            f"text.{name} must be sorted and non-overlapping"
    pairs = sorted(((b << 10) | (m - rules.mark_lo), c) for (b, m), c in rules.compose_table.items())
    L.append(f"/* {len(pairs)} canonical compositions from Unicode {unicodedata.unidata_version} */")
    L.append("const proto_compose_pair_t proto_compose_pairs[] = {")
    for i in range(0, len(pairs), 4):
        L.append("    " + " ".join(f"{{0x{k:08x}u, 0x{c:04x}u}}," for k, c in pairs[i:i + 4]))
    L += ["};", "const size_t proto_compose_pairs_count = sizeof(proto_compose_pairs) / sizeof(proto_compose_pairs[0]);", ""]
    ccc = [rules.ccc[cp] for cp in range(rules.mark_lo, rules.mark_hi + 1)]
    L.append("const uint8_t proto_mark_ccc[PROTO_TEXT_MARK_LAST - PROTO_TEXT_MARK_FIRST + 1] = {")
    for i in range(0, len(ccc), 16):
        L.append("    " + " ".join(f"{v}," for v in ccc[i:i + 16]))
    L += ["};", "", "const proto_cp_range_t proto_renderable_ranges[] = {"]
    for a, b in rules.ranges:
        L.append(f"    {{0x{a:04X}u, 0x{b:04X}u}},")
    L += ["};", "const size_t proto_renderable_ranges_count = sizeof(proto_renderable_ranges) / sizeof(proto_renderable_ranges[0]);", ""]
    L.append(f"/* {sum(b - a + 1 for a, b in rules.emoji)} emoji in {len(rules.emoji)} ranges (registry text.emoji_ranges) */")
    L.append("const proto_cp_range_t proto_emoji_ranges[] = {")
    for a, b in rules.emoji:
        L.append(f"    {{0x{a:04X}u, 0x{b:04X}u}},")
    L += ["};", "const size_t proto_emoji_ranges_count = sizeof(proto_emoji_ranges) / sizeof(proto_emoji_ranges[0]);", ""]
    L.append("const proto_cp_range_t proto_removed_ranges[] = {")
    for a, b in rules.removed:
        L.append(f"    {{0x{a:04X}u, 0x{b:04X}u}},")
    L += ["};", "const size_t proto_removed_ranges_count = sizeof(proto_removed_ranges) / sizeof(proto_removed_ranges[0]);", ""]
    return "\n".join(L)


# ----------------------------------------------------------------------------- JSON Schemas

AREA_OF_PREFIX = [("CAPABILITIES", "capabilities"), ("CONFIG_", "config"), ("TIME_SYNC", "config"), ("WIFI_", "config"),
                  ("APP", "apps"), ("NOTIF_", "notification"), ("XFER_", "transfer"), ("STORAGE_", "transfer"),
                  ("ASSET_", "transfer"), ("DEVICE_STATUS", "status"), ("PING", "status"), ("ERROR", "status")]


def area_of(name: str) -> str:
    for prefix, area in AREA_OF_PREFIX:
        if name.startswith(prefix):
            return area
    raise ValueError(f"no schema area for {name}")


def enum_doc(reg: R.Registry, name: str) -> str:
    if name == "status":
        vals = [(s["id"], s["name"]) for s in reg.raw["status_codes"]]
        return "status code: " + ", ".join(f"{v} {n}" for v, n in vals)
    e = reg.enums[name]
    return f"enum {name} (unknown values -> {e['fallback']}): " + ", ".join(f"{v['value']} {v['name']}" for v in e["values"])


def field_schema(reg: R.Registry, f: R.Field) -> dict:
    t = f.type
    if t in R.INT_WIDTH:
        w = R.INT_WIDTH[t]
        lo, hi = (-(1 << (8 * w - 1)), (1 << (8 * w - 1)) - 1) if t in R.SIGNED else (0, (1 << (8 * w)) - 1)
        s: dict = {"type": "integer", "minimum": f.min if f.min is not None else lo,
                   "maximum": f.max if f.max is not None else hi}
        doc = []
        if f.enum:
            doc.append(enum_doc(reg, f.enum))
        if f.bitmask:
            doc.append(f"bitmask {f.bitmask}: " + ", ".join(f"bit {b['bit']} {b['name']}" for b in reg.bitmasks[f.bitmask]))
        if f.description:
            doc.insert(0, f.description)
        if doc:
            s["description"] = "; ".join(doc)
    elif t == "bool":
        s = {"type": "boolean"}
    elif t == "struct":
        s = {"$ref": f"common.schema.json#/$defs/{f.struct}"}
    elif t == "bytes":
        s = {"type": "string", "pattern": "^([0-9a-f]{2})*$"}
        if f.eff_max_len:
            s["maxLength"] = 2 * f.eff_max_len
        if f.eff_min_len:
            s["minLength"] = 2 * f.eff_min_len
        s["description"] = "hex-encoded bytes"
    else:
        s = {"type": "string"}
        if t == "id":
            s["pattern"] = "^[a-z0-9_-][a-z0-9._-]{0,31}$"
        notes = [f"{t}: max {f.eff_max_len} UTF-8 bytes"] if f.eff_max_len else []
        if f.eff_min_len:
            notes.append(f"min {f.eff_min_len} bytes")
        if f.description:
            notes.insert(0, f.description)
        if f.eff_min_len:
            s["minLength"] = 1
        s["description"] = "; ".join(notes)
    if f.description and "description" not in s and t != "struct":
        s["description"] = f.description
    if f.repeated:
        s = {"type": "array", "items": s}
    return s


def object_schema(reg: R.Registry, fields: list[R.Field], description: str = "") -> dict:
    s = {"type": "object", "additionalProperties": False,
         "properties": {f.name: field_schema(reg, f) for f in sorted(fields, key=lambda f: f.tag)}}
    req = [f.name for f in sorted(fields, key=lambda f: f.tag) if f.required]
    if req:
        s["required"] = req
    if description:
        s["description"] = description
    return s


def message_schema(reg: R.Registry, m: R.Message) -> dict:
    return {"type": "object", "additionalProperties": False, "required": ["type", "fields"],
            "description": f"0x{m.id:02X} {m.kind} on {m.channel}. {m.description}".strip(),
            "properties": {"ver": {"const": reg.proto_major}, "type": {"const": m.name},
                           "req_id": {"type": "integer", "minimum": 0, "maximum": 65535},
                           "fields": object_schema(reg, m.fields)}}


def config_value_schema(reg: R.Registry, k: dict) -> dict:
    f = R.Field(tag=1, name=k["name"].replace(".", "_"), type=k["type"], min=k.get("min"), max=k.get("max"),
                max_len=k.get("max_len"), enum=k.get("enum"), bitmask=k.get("bitmask"))
    s = field_schema(reg, f)
    if k.get("enum"):
        s["enum"] = [v["value"] for v in reg.enums[k["enum"]]["values"]]
    s["default"] = k["default"]
    s["description"] = f"key {k['id']} (0x{k['id']:04X}), since {k['since']}" + \
        (f", variants {k['variants']}" if "variants" in k else "") + f". {k['description']}" + \
        (f" {s['description']}" if s.get("description") else "")
    return s


def gen_schemas(reg: R.Registry) -> dict[str, str]:
    out: dict[str, dict] = {}
    common = {"$schema": "https://json-schema.org/draft/2020-12/schema", "$id": SCHEMA_BASE + "common.schema.json",
              "title": "ePager shared structs", "$defs": {}}
    for sname, fields in reg.structs.items():
        common["$defs"][sname] = object_schema(reg, fields, reg.raw["structs"][sname].get("description", ""))
    common["$defs"]["status_code"] = {"type": "integer", "minimum": 0, "maximum": 255,
                                      "description": enum_doc(reg, "status")}
    out["common.schema.json"] = common

    areas: dict[str, list[R.Message]] = {}
    for m in reg.messages:
        areas.setdefault(area_of(m.name), []).append(m)
    for area, msgs in sorted(areas.items()):
        doc = {"$schema": "https://json-schema.org/draft/2020-12/schema", "$id": SCHEMA_BASE + f"{area}.schema.json",
               "title": f"ePager {area} messages (logical form, protocol.md 2.3)",
               "oneOf": [{"$ref": f"#/$defs/{m.name}"} for m in msgs],
               "$defs": {m.name: message_schema(reg, m) for m in msgs}}
        if area == "config":
            doc["$defs"]["config_values"] = {
                "type": "object", "additionalProperties": False,
                "description": "Typed view of config values by key name (registry config_keys).",
                "properties": {k["name"]: config_value_schema(reg, k) for k in reg.config_keys}}
        out[f"{area}.schema.json"] = doc
    out["message.schema.json"] = {
        "$schema": "https://json-schema.org/draft/2020-12/schema", "$id": SCHEMA_BASE + "message.schema.json",
        "title": "Any ePager message (logical form)",
        "oneOf": [{"$ref": f"{a}.schema.json"} for a in sorted(areas)]}
    return {k: json.dumps(v, indent=2, ensure_ascii=False) + "\n" for k, v in out.items()}


# ----------------------------------------------------------------------------- reference.md

def md_fields(reg: R.Registry, fields: list[R.Field]) -> list[str]:
    if not fields:
        return ["(no fields)", ""]
    L = ["| Tag | Field | Type | Req | Rep | Limits | Notes |", "|---|---|---|---|---|---|---|"]
    for f in sorted(fields, key=lambda f: f.tag):
        t = f"struct `{f.struct}`" if f.type == "struct" else f.type
        lim = []
        if f.eff_min_len:
            lim.append(f"min_len {f.eff_min_len}")
        if f.eff_max_len:
            lim.append(f"max_len {f.eff_max_len}")
        if f.min is not None:
            lim.append(f"min {f.min}")
        if f.max is not None:
            lim.append(f"max {f.max}")
        notes = []
        if f.enum:
            notes.append(f"enum `{f.enum}`")
        if f.bitmask:
            notes.append(f"bitmask `{f.bitmask}`")
        if f.description:
            notes.append(f.description)
        L.append(f"| {f.tag} | `{f.name}` | {t} | {'yes' if f.required else ''} | {'yes' if f.repeated else ''} "
                 f"| {', '.join(lim)} | {'; '.join(notes)} |")
    return L + [""]


def gen_reference(reg: R.Registry, gatt: dict) -> str:
    L = [f"<!-- {BANNER} -->", "# Protocol reference (generated)", "",
         f"Contract version **{reg.contract_version}**, protocol major **{reg.proto_major}**. "
         "Semantics are in [protocol.md](protocol.md).", "", "## GATT", "",
         "| Characteristic | UUID | Properties | Security |", "|---|---|---|---|",
         f"| (service) | `{gatt['service']['uuid']}` | | |"]
    for c in gatt["service"]["characteristics"]:
        L.append(f"| {c['name']} | `{c['uuid']}` | {', '.join(c['properties'])} | {c['security']} |")
    tcp = gatt["tcp"]
    L += ["", f"Advertised name prefix: `{gatt['advertising']['name_prefix']}`.", "",
          f"TCP development transport (fake board only): default port {tcp['default_port']}, value at most "
          f"{tcp['max_value']} bytes, ops " + ", ".join(f"{v} `{k}`" for k, v in tcp["ops"].items()) + "."]
    L += ["", "## Limits", "", "| Limit | Value |", "|---|---|"]
    L += [f"| `{k}` | {v} |" for k, v in reg.limits.items()]
    L += ["", "## Messages", "", "| ID | Name | Kind | Channel |", "|---|---|---|---|"]
    L += [f"| 0x{m.id:02X} | [`{m.name}`](#{m.name.lower()}) | {m.kind} | {m.channel} |"
          for m in sorted(reg.messages, key=lambda m: m.id)]
    L.append("")
    for m in sorted(reg.messages, key=lambda m: m.id):
        L += [f"### {m.name}", "", f"0x{m.id:02X}, {m.kind}, channel `{m.channel}`. {m.description}".strip(), ""]
        L += md_fields(reg, m.fields)
    L += ["## Structs", ""]
    for sname, fields in reg.structs.items():
        L += [f"### `{sname}`", "", reg.raw["structs"][sname].get("description", ""), ""]
        L += md_fields(reg, fields)
    L += ["## Status codes", "", "| ID | Name | Meaning |", "|---|---|---|"]
    L += [f"| {s['id']} | `{s['name']}` | {s['description']} |" for s in reg.raw["status_codes"]]
    L += ["", "## Enums", ""]
    for ename, e in reg.enums.items():
        L.append(f"- `{ename}` (fallback {e['fallback']}): " + ", ".join(
            f"{v['value']} `{v['name']}`" + (f" ({v['description']})" if "description" in v else "") for v in e["values"]))
    L += ["", "## Bitmasks", ""]
    for bname, bits in reg.bitmasks.items():
        L.append(f"- `{bname}`: " + ", ".join(f"bit {b['bit']} `{b['name']}`" for b in bits))
    L += ["", "## Config keys", "", "| ID | Name | Type | Range / enum | Default | Variants | Since | Description |",
          "|---|---|---|---|---|---|---|---|"]
    for k in reg.config_keys:
        rng = f"enum `{k['enum']}`" if "enum" in k else (f"bitmask `{k['bitmask']}`" if "bitmask" in k else "")
        if "min" in k or "max" in k:
            rng = f"{k.get('min', '')}..{k.get('max', '')}"
        if "max_len" in k:
            rng = f"max_len {k['max_len']}"
        L.append(f"| 0x{k['id']:04X} | `{k['name']}` | {k['type']} | {rng} | `{json.dumps(k['default'])}` "
                 f"| {', '.join(k.get('variants', [])) or 'all'} | {k['since']} | {k['description']} |")
    L.append("")
    return "\n".join(L)


