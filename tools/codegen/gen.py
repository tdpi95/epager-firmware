def outputs() -> dict[Path, str]:
    reg = R.load()
    gatt = json.loads((R.CONTRACTS / "gatt.json").read_text())
    out = {HDR: gen_header(reg, gatt), SRC: gen_source(reg), REFERENCE: gen_reference(reg, gatt)}
    for name, content in gen_schemas(reg).items():
        out[SCHEMAS / name] = content
    return out


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--check", action="store_true")
    args = ap.parse_args()
    stale = []
    for path, content in outputs().items():
        if args.check:
            if not path.exists() or path.read_text() != content:
                stale.append(path.relative_to(REPO))
        else:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text(content)
    if stale:
        print("stale generated files (run tools/codegen/gen.py):", *stale, sep="\n  ")
        return 1
    if args.check:
        print("generated files up to date")
    return 0


if __name__ == "__main__":
    sys.exit(main())
